/// 단계별 레시피 필터링
List<Recipe> getRecipesByStage(BabyFoodStage stage) {
  return defaultRecipes.where((r) => r.stage == stage).toList();
}

/// ID로 레시피 찾기
Recipe? findRecipeById(String id) {
  try {
    return defaultRecipes.firstWhere((r) => r.id == id);
  } catch (e) {
    return null;
  }
}
