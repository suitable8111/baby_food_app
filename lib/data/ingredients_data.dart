/// ID로 식재료 찾기
Ingredient? findIngredientById(String id) {
  try {
    return defaultIngredients.firstWhere((i) => i.id == id);
  } catch (e) {
    return null;
  }
}

/// 카테고리별 식재료 필터링
List<Ingredient> getIngredientsByCategory(IngredientCategory category) {
  return defaultIngredients.where((i) => i.category == category).toList();
}

/// 단계별 사용 가능 식재료 필터링
List<Ingredient> getIngredientsByStage(BabyFoodStage stage) {
  return defaultIngredients.where((i) => i.isAvailableAt(stage)).toList();
}
